// Ensure convenient title and description aliases are defined across all theme entries
for (const theme of Object.values(THEME_SEO_DATA)) {
  if (!theme.title) theme.title = theme.metaTitle
  if (!theme.description) theme.description = theme.metaDescription
}

export const ALL_THEME_SLUGS = Object.keys(THEME_SEO_DATA)

export function getAllThemes() {
  return Object.values(THEME_SEO_DATA)
}

export function getThemeBySlug(slug) {
  if (!slug) return null
  const clean = String(slug).trim().toLowerCase()
  return THEME_SEO_DATA[clean] || null
}

/**
 * Filter templates matching a theme slug.
 * If templatesList is provided, returns matching template objects from that list.
 * If templatesList is omitted or null, returns the curatedTemplateSlugs array.
 */
export function getMatchingTemplatesForTheme(themeSlug, templatesList = null) {
  const theme = getThemeBySlug(themeSlug)
  if (!theme) return []
  const curated = theme.curatedTemplateSlugs || []
  if (!templatesList || !Array.isArray(templatesList)) {
    return curated
  }
  return templatesList.filter((tpl) => {
    const slug = (tpl?.slug || '').toLowerCase().trim()
    return curated.includes(slug)
  })
}

/**
 * Helper to resolve SEO metadata for a theme path, compatible with both
 * client-side routers and Cloudflare Pages Functions middleware.
 */
export function resolveThemeSeo(pathname) {
  if (!pathname) return null
  const match = pathname.match(/^\/tema\/([^/]+)$/)
  if (!match) return null

  const theme = getThemeBySlug(match[1])
  if (!theme) return null

  const origin = 'https://www.satuundangan.id'
  const canonical = `${origin}/tema/${theme.slug}`

  return {
    title: theme.title || theme.metaTitle,
    description: theme.description || theme.metaDescription,
    canonical,
    ogImage: `${origin}/og-image-v1.jpg`,
    ogType: 'website',
    url: canonical,
  }
}

